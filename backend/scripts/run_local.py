"""Run CareerLine locally with no Docker.

    python scripts/run_local.py            # app on http://127.0.0.1:8080
    python scripts/run_local.py --dev      # API with reload on :8000 + Vite dev server on :5173
    python scripts/run_local.py --rebuild  # force a fresh frontend build first
    python scripts/run_local.py --demo     # demo mode: fictional data in a separate database
    python scripts/run_local.py --verify-backup FILE   # check that a backup opens, then exit
    python scripts/run_local.py --restore FILE         # restore into an EMPTY database, then exit
    python scripts/run_local.py --rotate-key   # new encryption key first in .env, re-encrypt, exit
    python scripts/run_local.py --key-status   # which encryption keys are still in use, then exit

What it does:
1. Creates ``<repo>/.env`` with a fresh encryption key the first time (never commit it).
2. Starts the embedded PostgreSQL (data in ``<repo>/.localdata/pg``).
3. Applies database migrations.
4. Starts the background worker (job sources, scoring, notifications, backups).
5. Builds the frontend if needed, and serves it and the API from one origin.

Encrypted backups go to ``<repo>/.localdata/backups`` unless CAREERLINE_BACKUP_DIR is set.
"""

from __future__ import annotations

import argparse
import os
import shutil
import socket
import subprocess
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
REPO = BACKEND.parent
FRONTEND = REPO / "frontend"
ENV_FILE = REPO / ".env"
BACKUPS = REPO / ".localdata" / "backups"
DEMO_DATA = REPO / ".localdata" / "pg-demo"

sys.path.insert(0, str(BACKEND / "scripts"))
sys.path.insert(0, str(BACKEND))

import localdb  # noqa: E402

from careerline.security.crypto import generate_key  # noqa: E402

ENV_TEMPLATE = """\
# CareerLine local settings. Generated by scripts/run_local.py.
# KEEP THIS FILE PRIVATE AND BACKED UP: without the encryption key, encrypted
# fields (such as two-factor secrets) can't be read.
CAREERLINE_ENV=production
CAREERLINE_ENCRYPTION_KEYS=1:{key}
# Plain http on localhost, so cookies can't be marked Secure. Set to true behind HTTPS.
CAREERLINE_COOKIE_SECURE=false
CAREERLINE_HSTS=false
CAREERLINE_ALLOW_REGISTRATION=false
"""


def load_env_file() -> dict[str, str]:
    if not ENV_FILE.exists():
        ENV_FILE.write_text(ENV_TEMPLATE.format(key=generate_key()), encoding="utf-8")
        print(f"Created {ENV_FILE} with a new encryption key. Back it up.")
    values: dict[str, str] = {}
    for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            values[k.strip()] = v.strip()
    return values


KEYS_VAR = "CAREERLINE_ENCRYPTION_KEYS"


def server_running(port: int) -> bool:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.settimeout(0.5)
        return sock.connect_ex(("127.0.0.1", port)) == 0


def rotate_env_key(port: int) -> str:
    """Put a fresh key first in .env's CAREERLINE_ENCRYPTION_KEYS (old keys stay after it).

    Returns the new key's version. Exits with a message when it can't do it safely."""
    if KEYS_VAR in os.environ:
        sys.exit(
            f"{KEYS_VAR} is set in the environment, not only in .env. Put a new key first "
            "there yourself, then run with --rekey."
        )
    if server_running(port):
        sys.exit(
            f"CareerLine seems to be running on port {port}. Stop it first: an app still "
            "using the old key list can't read values written with the new key."
        )
    lines = ENV_FILE.read_text(encoding="utf-8").splitlines(keepends=True)
    index = next(
        (i for i, line in enumerate(lines) if line.strip().startswith(f"{KEYS_VAR}=")), None
    )
    if index is None:
        sys.exit(f"{ENV_FILE} has no {KEYS_VAR} line to update.")
    current = lines[index].split("=", 1)[1].strip()
    versions = [entry.split(":", 1)[0].strip() for entry in current.split(",") if entry.strip()]
    numbers = [int(v) for v in versions if v.isdigit()]
    version = str(max(numbers, default=0) + 1)
    while version in versions:
        version = str(int(version) + 1)
    lines[index] = f"{KEYS_VAR}={version}:{generate_key()},{current}\n"
    tmp = ENV_FILE.with_name(ENV_FILE.name + ".tmp")
    tmp.write_text("".join(lines), encoding="utf-8")
    os.replace(tmp, ENV_FILE)
    print(f"Added encryption key {version} to {ENV_FILE.name} (older keys kept after it).")
    return version


def npm() -> str:
    exe = shutil.which("npm.cmd") or shutil.which("npm")
    if not exe:
        sys.exit("npm was not found. Install Node.js 20+ and try again.")
    return exe


def ensure_frontend_build(force: bool) -> Path:
    dist = FRONTEND / "dist"
    if force or not (dist / "index.html").exists():
        if not (FRONTEND / "node_modules").exists():
            subprocess.run([npm(), "ci"], cwd=FRONTEND, check=True)  # noqa: S603
        subprocess.run([npm(), "run", "build"], cwd=FRONTEND, check=True)  # noqa: S603
    return dist


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--dev", action="store_true", help="hot-reload API + Vite dev server")
    parser.add_argument("--rebuild", action="store_true", help="rebuild the frontend first")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument(
        "--fresh", action="store_true", help="DELETE the database first (test runs only)"
    )
    parser.add_argument(
        "--pgdata", type=Path, default=localdb.DATA, help="Postgres data directory (for test runs)"
    )
    parser.add_argument(
        "--no-worker", action="store_true", help="Don't start the background worker"
    )
    parser.add_argument(
        "--demo",
        action="store_true",
        help="demo mode: fictional data in its own database (.localdata/pg-demo)",
    )
    parser.add_argument("--verify-backup", type=Path, help="decrypt and check a backup, then exit")
    parser.add_argument(
        "--restore", type=Path, help="restore a backup into an empty database, then exit"
    )
    parser.add_argument(
        "--rotate-key",
        action="store_true",
        help="add a new encryption key to .env, re-encrypt everything with it, then exit",
    )
    parser.add_argument(
        "--rekey",
        action="store_true",
        help="re-encrypt everything with the first key in CAREERLINE_ENCRYPTION_KEYS, then exit",
    )
    parser.add_argument(
        "--key-status", action="store_true", help="show which encryption keys are in use, then exit"
    )
    args = parser.parse_args()
    if args.rotate_key:
        load_env_file()  # creates .env on a first run
        rotate_env_key(args.port)
    elif args.rekey and server_running(args.port):
        sys.exit(f"CareerLine seems to be running on port {args.port}. Stop it first.")

    # Real environment variables win over .env, as with pydantic-settings and Docker.
    env = {**load_env_file(), **os.environ}
    if args.demo:
        # Never mix demo data with real data, and never back it up.
        if args.pgdata.resolve() == localdb.DATA.resolve():
            args.pgdata = DEMO_DATA
        env["CAREERLINE_DEMO_MODE"] = "true"
        env["CAREERLINE_BACKUP_DIR"] = ""
        print("Demo mode: sign in as demo@example.com / explore-careerline")
    elif args.pgdata.resolve() == localdb.DATA.resolve():
        # Backups on by default for the real database only, never for test databases.
        env.setdefault("CAREERLINE_BACKUP_DIR", str(BACKUPS))
    else:
        env["CAREERLINE_BACKUP_DIR"] = ""

    print("Starting local PostgreSQL…")
    srv = localdb._server(args.pgdata)
    if args.fresh:
        if args.pgdata.resolve() == localdb.DATA.resolve():
            sys.exit("--fresh is refused for the main data directory; use --pgdata.")
        srv.psql(f'DROP DATABASE IF EXISTS "{localdb.DB_NAME}" WITH (FORCE);')  # type: ignore[attr-defined]
    localdb.ensure_database(srv, localdb.DB_NAME)
    env["CAREERLINE_DATABASE_URL"] = localdb.tcp_url(srv, localdb.DB_NAME)

    print("Applying migrations…")
    py = sys.executable
    subprocess.run([py, "-m", "alembic", "upgrade", "head"], cwd=BACKEND, env=env, check=True)  # noqa: S603

    if args.rotate_key or args.rekey or args.key_status:
        command = "keys" if args.key_status else "rekey"
        code = subprocess.run(  # noqa: S603
            [py, "-m", "careerline.data", command], cwd=BACKEND, env=env
        ).returncode
        if code == 0 and command == "rekey":
            print(
                "\nNext: start CareerLine and make a fresh backup (Settings > Data > Back up now). "
                "Remove the old key from .env once --key-status says it's unused and the "
                "backups made before today have expired."
            )
        return code

    if args.verify_backup or args.restore:
        target = args.verify_backup or args.restore
        command = "verify" if args.verify_backup else "restore"
        return subprocess.run(  # noqa: S603
            [py, "-m", "careerline.data", command, str(target.resolve())], cwd=BACKEND, env=env
        ).returncode

    uvicorn = [
        py,
        "-m",
        "uvicorn",
        "careerline.main:create_app",
        "--factory",
        "--host",
        "127.0.0.1",
    ]
    # Background worker: job-source fetches, scoring, reminders, backups.
    worker = None
    if not args.no_worker:
        worker = subprocess.Popen([py, "-m", "careerline.worker"], cwd=BACKEND, env=env)  # noqa: S603

    def stop_worker() -> None:
        if worker is not None and worker.poll() is None:
            worker.terminate()
            try:
                worker.wait(timeout=10)
            except subprocess.TimeoutExpired:
                worker.kill()

    if args.dev:
        env["CAREERLINE_ENV"] = "development"
        env.pop("CAREERLINE_STATIC_DIR", None)
        api = subprocess.Popen([*uvicorn, "--port", "8000", "--reload"], cwd=BACKEND, env=env)  # noqa: S603
        web = subprocess.Popen([npm(), "run", "dev"], cwd=FRONTEND, env=env)  # noqa: S603
        print(
            "\nCareerLine dev servers: http://localhost:5173  (API docs: http://localhost:8000/api/docs)\n"
        )
        try:
            return web.wait()
        except KeyboardInterrupt:
            return 0
        finally:
            for p in (web, api):
                p.terminate()
            stop_worker()

    env["CAREERLINE_STATIC_DIR"] = str(ensure_frontend_build(args.rebuild))
    print(f"\nCareerLine is running at http://localhost:{args.port}  (Ctrl+C to stop)\n")
    try:
        return subprocess.run([*uvicorn, "--port", str(args.port)], cwd=BACKEND, env=env).returncode  # noqa: S603
    except KeyboardInterrupt:
        return 0
    finally:
        stop_worker()


if __name__ == "__main__":
    sys.exit(main())
